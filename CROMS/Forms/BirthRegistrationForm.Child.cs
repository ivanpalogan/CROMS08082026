        private void SetBirthOrder(string stored)
        {
            string v = BirthOrderText.Normalize(stored);
            if (v.Length == 0) { _cboBirthOrder.SelectedIndex = 0; return; }
            int idx = _cboBirthOrder.Items.IndexOf(v);
            if (idx < 0) { _cboBirthOrder.Items.Add(v); idx = _cboBirthOrder.Items.Count - 1; }  // never hide what a record holds
            _cboBirthOrder.SelectedIndex = idx;
        }

        // ------------------------------------------------------------------ multiple birth (5b)
        private void ApplyMultipleBirth()
        {
            string type = (cboTypeOfBirth.Text ?? "").Trim();
            bool multiple = type.Length > 0 && !string.Equals(type, "Single", StringComparison.OrdinalIgnoreCase);
            lblMultiple.Enabled = multiple;
            cboMultiple.Enabled = multiple;
            if (!multiple) cboMultiple.SelectedIndex = -1;   // a single birth cannot be the 2nd of a set
        }

        private object MultipleBirthParam()
        {
            string v = cboMultiple.Enabled ? (cboMultiple.Text ?? "").Trim() : "";
            return v.Length == 0 ? (object)DBNull.Value : v;
        }

        private void SetMultipleBirth(string stored)
        {
            ApplyMultipleBirth();
            string v = BirthOrderText.Normalize(stored);
            if (v.Length == 0) { cboMultiple.SelectedIndex = -1; return; }
            int idx = cboMultiple.Items.IndexOf(v);
            if (idx < 0) { cboMultiple.Items.Add(v); idx = cboMultiple.Items.Count - 1; }
            cboMultiple.SelectedIndex = idx;
        }

        // ------------------------------------------------------------------ time of birth
        private static readonly string[] TimeFormats =
            { "HH:mm", "H:mm", "hh:mm tt", "h:mm tt", "HH:mm:ss", "h:mm:ss tt", "hh:mmtt", "h:mmtt" };

        /// <summary>Stored as HH:mm (24 h) - what every existing row already holds.</summary>
        private object TimeOfBirthParam()
        {
            if (dtpTimeOfBirth.Checked) return dtpTimeOfBirth.Value.ToString("HH:mm", CultureInfo.InvariantCulture);
            return string.IsNullOrWhiteSpace(_timeRaw) ? (object)DBNull.Value : _timeRaw;
        }

        private void SetTimeOfBirth(string stored)
        {
            _timeRaw = null;
            if (string.IsNullOrWhiteSpace(stored)) { dtpTimeOfBirth.Checked = false; return; }
            DateTime t;
            if (DateTime.TryParseExact(stored.Trim(), TimeFormats, CultureInfo.InvariantCulture, DateTimeStyles.AllowWhiteSpaces, out t))
            {
                dtpTimeOfBirth.Value = DateTime.Today.Add(t.TimeOfDay);
                dtpTimeOfBirth.Checked = true;
            }
            else
            {
                dtpTimeOfBirth.Checked = false;
                _timeRaw = stored.Trim();   // not a clock time: keep it, do not erase it on save
            }
        }

