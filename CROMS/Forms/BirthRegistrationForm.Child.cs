        // ------------------------------------------------------------------ registration fee
        /// <summary>Shows the fee already recorded for this record (locked: an O.R. is issued
        /// once) or leaves the boxes open for a new one.</summary>
        private void LoadRegistrationFee(int birthId)
        {
            _feeRecorded = false;
            txtFee.ReadOnly = txtFeeOr.ReadOnly = false;
            txtFee.Text = txtFeeOr.Text = "";
            try
            {
                using (DataTable dt = Db.Pull(
                    "SELECT or_number, net_amount FROM payments WHERE source_table = 'births' AND source_id = @id ORDER BY id LIMIT 1",
                    new MySqlParameter("@id", birthId)))
                {
                    if (dt.Rows.Count == 0) return;
                    txtFee.Text = Convert.ToDecimal(dt.Rows[0]["net_amount"]).ToString("0.00", CultureInfo.InvariantCulture);
                    txtFeeOr.Text = Convert.ToString(dt.Rows[0]["or_number"]);
                    txtFee.ReadOnly = txtFeeOr.ReadOnly = true;
                    _feeRecorded = true;
                }
            }
            catch { /* the fee is information here - a read failure must not stop the record opening */ }
        }

        private void ResetRegistrationFee()
        {
            _feeRecorded = false;
            if (txtFee == null) return;
            txtFee.ReadOnly = txtFeeOr.ReadOnly = false;
            txtFee.Text = txtFeeOr.Text = "";
        }

        /// <summary>Inline checks for the fee boxes, folded into ValidateChild.</summary>
        private void ValidateRegistrationFee(Action<Control, TabPage, string[]> flag)
        {
            if (_feeRecorded) return;
            string amt = txtFee.Text.Trim(), or = txtFeeOr.Text.Trim();
            if (amt.Length == 0 && or.Length == 0) return;

            decimal a;
            if (!decimal.TryParse(amt, NumberStyles.Number, CultureInfo.InvariantCulture, out a) || a <= 0)
                flag(txtFee, tabCert, new[] { "Enter the fee amount collected.", "Enter the amount." });
            if (or.Length == 0)
            {
                flag(txtFeeOr, tabCert, new[] { "Enter the Treasury Official Receipt number for this fee.", "Enter the O.R. number." });
                return;
            }
            DataRow dup = PaymentService.FindByOr(or);
            bool mine = dup != null && _editingId.HasValue && (dup["source_table"] as string) == "births" &&
                        dup["source_id"] != DBNull.Value && Convert.ToInt32(dup["source_id"]) == _editingId.Value;
            if (dup != null && !mine)
                flag(txtFeeOr, tabCert, new[] { "O.R. " + or + " is already recorded for another payment.", "O.R. already used." });
        }

        /// <summary>
        /// Writes the typed fee into the payment log, linked to this record. Never for a Draft
        /// (an O.R. is not spent on a record that is not yet official) and only once per record.
        /// A failure is reported but does not undo the registration - the record is already saved
        /// and the fee can be recorded again from Fees &amp; Payments.
        /// </summary>
        private void RecordRegistrationFee(long birthId, string status, IWin32Window owner)
        {
            if (_feeRecorded || string.Equals(status, "Draft", StringComparison.OrdinalIgnoreCase)) return;
            string amt = txtFee.Text.Trim(), or = txtFeeOr.Text.Trim();
            if (amt.Length == 0 && or.Length == 0) return;
            try
            {
                decimal a = decimal.Parse(amt, NumberStyles.Number, CultureInfo.InvariantCulture);
                string child = (txtLastName.Text.Trim() + ", " + txtFirstName.Text.Trim()).Trim(' ', ',');
                var e = new PaymentEntry
                {
                    Source = PaymentService.SourceBirth,
                    SourceTable = "births",
                    SourceId = (int)birthId,
                    PayerName = string.IsNullOrWhiteSpace(txtInfName.Text) ? child : txtInfName.Text.Trim(),
                    Purpose = "Birth registration" + (chkDelayed.Checked ? " (delayed)" : "") + " - " + child,
                    OrNumber = or,
                    Method = "Cash"
                };
                e.Lines.Add(new PaymentLine
                {
                    FeeCode = "REG-BIRTH",
                    Description = "Registration - Birth (Municipal Form 102)" + (chkDelayed.Checked ? " - delayed registration" : ""),
                    Quantity = 1,
                    UnitAmount = a
                });
                PaymentService.RecordForModule(e, Session.User == null ? (int?)null : Session.User.Id);
                _feeRecorded = true;
            }
            catch (Exception ex)
            {
                ErrorLog.Write("BirthRegistrationForm.RecordRegistrationFee", ex);
                // An O.R. already used / bad amount is a rule with its own sentence; anything else is a fault.
                string why = ex is InvalidOperationException ? ex.Message : ErrorLog.Friendly(ex, "record the fee for");
                MessageBox.Show(owner, "The record was saved, but the registration fee was NOT recorded.\n\n" + why +
                    "\n\nRecord it from Fees & Payments (walk-in payment).", "Registration fee",
                    MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
        }
    }
