    /// <summary>Birth order as the paper form writes it: 1st, 2nd, 3rd ...</summary>
    internal static class BirthOrderText
    {
        public const int Max = 20;

        public static string Ordinal(int n)
        {
            int t = n % 100;
            string s = (t >= 11 && t <= 13) ? "th" : (n % 10 == 1 ? "st" : n % 10 == 2 ? "nd" : n % 10 == 3 ? "rd" : "th");
            return n + s;
        }

        public static IEnumerable<string> Items()
        {
            for (int i = 1; i <= Max; i++) yield return Ordinal(i);
        }

        private static readonly string[] Words =
        {
            "first", "second", "third", "fourth", "fifth", "sixth", "seventh", "eighth", "ninth", "tenth",
            "eleventh", "twelfth", "thirteenth", "fourteenth", "fifteenth", "sixteenth", "seventeenth",
            "eighteenth", "nineteenth", "twentieth"
        };

        /// <summary>
        /// "First", "1", "01" and "1st" all become "1st". Anything that is none of those is
        /// returned exactly as it was read - never guessed at.
        /// </summary>
        public static string Normalize(string text)
        {
            if (string.IsNullOrWhiteSpace(text)) return "";
            string t = text.Trim();
            int w = Array.IndexOf(Words, t.ToLowerInvariant());
            if (w >= 0) return Ordinal(w + 1);
            string digits = t.ToLowerInvariant();
            foreach (string suffix in new[] { "st", "nd", "rd", "th" })
                if (digits.EndsWith(suffix, StringComparison.Ordinal)) { digits = digits.Substring(0, digits.Length - 2); break; }
            int n;
            if (int.TryParse(digits, NumberStyles.None, CultureInfo.InvariantCulture, out n) && n >= 1 && n <= Max)
                return Ordinal(n);
            return t;
        }
    }

